// Index of a character can be printed

let firstName = "Kannan"
console.log(firstName.indexOf("a")) // 1 is printed since a is in the index number 1
console.log(firstName.indexOf("n")) // 2 is printed directly since the first n is at the index number 2
console.log(firstName.indexOf("n",4)) // 5 is printed since the end index is specified as 4 and the last n is at the index number 5 